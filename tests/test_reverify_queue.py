"""scripts/reverify_queue.py keeps marks and unfinished items across weekly regeneration."""
from conftest import load

rq = load("reverify_queue", "scripts/reverify_queue.py")

NEW = """# Re-verification queue — 2026-10-12

Generated by scripts/weekly-maintenance.sh.

- [ ] `wiki/a.md` — cites `raw/x.md` (changed)
- [ ] `wiki/b.md` — cites `raw/y.md` (changed)
"""
OLD = """# Re-verification queue — 2026-10-05

- [~] `wiki/a.md` — cites `raw/x.md` (changed)
- [x] `wiki/b.md` — cites `raw/y.md` (changed)
- [ ] `wiki/c.md` — cites `raw/z.md` (changed)
- [-] `wiki/d.md` — cites `raw/w.md` (changed)
"""


def never(path):
    return None


def test_marks_survive_and_done_resets():
    out = rq.merge(NEW, [OLD], "", verified=never)
    assert "- [~] `wiki/a.md`" in out          # reviewing mark kept
    assert "- [ ] `wiki/b.md`" in out          # done earlier, source changed again: pending
    assert "wiki/d.md" not in out              # rejected and no longer regenerated: dropped


def test_unfinished_items_are_carried_over(tmp_path, monkeypatch):
    monkeypatch.chdir(tmp_path)
    (tmp_path / "wiki").mkdir()
    (tmp_path / "wiki/c.md").write_text("---\nlast_verified: 2026-09-01\n---\n")
    out = rq.merge(NEW, [OLD], "", verified=rq.page_verified)
    assert "## Carried over from earlier weeks" in out
    assert "- [ ] `wiki/c.md`" in out


def test_carried_item_is_dropped_once_page_was_verified_after_queueing(tmp_path, monkeypatch):
    monkeypatch.chdir(tmp_path)
    (tmp_path / "wiki").mkdir()
    (tmp_path / "wiki/c.md").write_text("---\nlast_verified: 2026-10-08\n---\n")
    out = rq.merge(NEW, [OLD], "", verified=rq.page_verified)
    assert "wiki/c.md" not in out


def test_missing_page_is_dropped(tmp_path, monkeypatch):
    monkeypatch.chdir(tmp_path)
    out = rq.merge(NEW, [OLD], "", verified=rq.page_verified)
    assert "wiki/c.md" not in out


def test_ingest_item_resolves_when_file_is_cited():
    old = "# Re-verification queue — 2026-10-05\n\n- [ ] ingest `raw/docs/changelog-1-to-2.md` into [[whats-new]]\n"
    assert "ingest" in rq.merge(NEW, [old], "", verified=never)
    assert "ingest" not in rq.merge(NEW, [old], "sources: raw/docs/changelog-1-to-2.md", verified=never)


def test_newest_old_queue_wins_for_marks():
    newer = "# Re-verification queue — 2026-10-05\n\n- [-] `wiki/a.md` — cites `raw/x.md` (changed)\n"
    older = "# Re-verification queue — 2026-09-28\n\n- [~] `wiki/a.md` — cites `raw/x.md` (changed)\n"
    assert "- [-] `wiki/a.md`" in rq.merge(NEW, [newer, older], "", verified=never)
