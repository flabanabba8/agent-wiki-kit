#!/usr/bin/env python3
"""build-context-guide.py - keep a generated map of the wiki inside CLAUDE.md (and so AGENTS.md).

Why: an agent that reads CLAUDE.md at session start should know which pages exist without
loading wiki/index.md, and a hand-kept list drifts. This compiles the folder-by-folder page
list from the real wiki/ tree into a bounded block between two markers. Nothing outside the
markers is touched.

  build-context-guide.py            rewrite the block (inserts it before "## Page frontmatter"
                                    the first time)
  build-context-guide.py --check    exit 1 when the block is missing or stale; changes nothing

The block is capped at MAX_CHARS. Past that, each folder keeps its first slugs and ends "+N more".
Standard library only.
"""
import os
import re
import subprocess
import sys

START = "<!-- wiki-map:start (generated by scripts/build-context-guide.py; do not edit) -->"
END = "<!-- wiki-map:end -->"
MAX_CHARS = 3500
TARGET = "CLAUDE.md"


def root():
    out = subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True).stdout.strip()
    return out or os.getcwd()


def pages(base):
    folders = {}
    wiki = os.path.join(base, "wiki")
    for name in sorted(os.listdir(wiki)):
        d = os.path.join(wiki, name)
        if not os.path.isdir(d):
            continue
        slugs = sorted(f[:-3] for f in os.listdir(d) if f.endswith(".md"))
        if slugs:
            folders[name] = slugs
    return folders


def render(folders, limit=None):
    total = sum(len(v) for v in folders.values())
    lines = [START, "## Wiki map (generated)", "",
             f"{total} pages under `wiki/<folder>/<slug>.md`. Run the semantic query first; "
             "`wiki/index.md` has a one-line summary per page.", ""]
    for name, slugs in folders.items():
        shown = slugs if limit is None else slugs[:limit]
        extra = len(slugs) - len(shown)
        lines.append(f"- **{name}** ({len(slugs)}): " + ", ".join(shown) + (f", +{extra} more" if extra else ""))
    lines.append(END)
    return "\n".join(lines)


def compile_block(folders):
    block = render(folders)
    limit = max((len(v) for v in folders.values()), default=0)
    while len(block) > MAX_CHARS and limit > 1:
        limit -= 1
        block = render(folders, limit)
    return block


def apply(text, block):
    if START in text and END in text:
        head, rest = text.split(START, 1)
        _, tail = rest.split(END, 1)
        return head + block + tail
    marker = "## Page frontmatter"
    if marker in text:
        head, tail = text.split(marker, 1)
        return head + block + "\n\n" + marker + tail
    return text.rstrip("\n") + "\n\n" + block + "\n"


def main(argv):
    base = root()
    path = os.path.join(base, TARGET)
    text = open(path, encoding="utf-8").read()
    new = apply(text, compile_block(pages(base)))
    if "--check" in argv:
        if new != text:
            print("wiki map in CLAUDE.md is missing or stale: run scripts/build-context-guide.py")
            return 1
        print("wiki map in CLAUDE.md is current")
        return 0
    if new != text:
        with open(path, "w", encoding="utf-8") as f:
            f.write(new)
        print("rewrote the wiki map in CLAUDE.md")
    else:
        print("wiki map already current")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
